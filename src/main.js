/* =========================================================
   MAIN BOOTSTRAP — wires everything together for the WEB
   build. Poki/CrazyGames builds get their own boot file
   generated by build.js which selects the right adapter.
   ========================================================= */

import { createWebPlatform } from "../platform/web/web.js";
import { setPlatform } from "./ui/platform-bridge.js";
import { initBoard } from "./ui/board.js";
import {
    initScreens,
    showMenu,
    showModeSelect,
    hideDifficulty,
    playNow,
    onCellClick,
    launchClassicLocal,
    launchMode,
    launchWithDifficulty,
    goHome,
    openSettings,
    openStats,
    getSession
} from "./ui/screens.js";
import { initThemeFromProgress } from "./ui/themes.js";
import { initAudio, play, toggleSound } from "./audio/audio.js";
import { maybeShowOnboarding } from "./ui/onboarding.js";

/* ---------------------------------------------------------
   Platform setup
   --------------------------------------------------------- */

const platform = createWebPlatform();
setPlatform(platform);

/* ---------------------------------------------------------
   DOM references
   --------------------------------------------------------- */

const $ = (id) => document.getElementById(id);

const app = $("app");
const loadingScreen = $("loadingScreen");
const boardEl = $("board");

const modeButtons = {
    modeClassicLocal: () => launchClassicLocal(),
    modeClassicAi: () => launchMode("classic-ai"),
    modeStreak: () => launchMode("streak"),
    modeTimed: () => launchMode("timed"),
    modeChallenge: () => launchMode("challenge"),
    modeTournament: () => launchMode("tournament"),
    modeDaily: () => launchMode("daily")
};

/* ---------------------------------------------------------
   Event wiring
   --------------------------------------------------------- */

function wireEvents() {
    // Lobby: primary action — one tap into a match.
    const playNowBtn = $("playNowBtn");
    if (playNowBtn) {
        playNowBtn.addEventListener("click", () => {
            initAudio();
            playNow();
        });
    }

    // Lobby: secondary modes screen.
    const modesBtn = $("modesBtn");
    if (modesBtn) {
        modesBtn.addEventListener("click", () => {
            initAudio();
            play("click");
            showModeSelect();
        });
    }

    const modesBack = $("modesBack");
    if (modesBack) {
        modesBack.addEventListener("click", () => {
            play("click");
            showMenu();
        });
    }

    // Difficulty chips (AI modes) — wire by data-difficulty if present,
    // otherwise by the legacy diff* ids.
    const difficultyChips = document.querySelectorAll("[data-difficulty]");
    const difficultyMap = {
        diffEasy: "easy",
        diffMedium: "medium",
        diffHard: "hard",
        diffImpossible: "impossible"
    };

    const wireDifficulty = (el, value) => {
        el.addEventListener("click", () => {
            initAudio();
            play("click");
            launchWithDifficulty(value);
        });
    };

    difficultyChips.forEach((el) => wireDifficulty(el, el.dataset.difficulty));
    for (const [buttonId, difficulty] of Object.entries(difficultyMap)) {
        const button = $(buttonId);
        if (button && !button.dataset.difficulty) {
            wireDifficulty(button, difficulty);
        }
    }

    // Mode selection.
    for (const [buttonId, handler] of Object.entries(modeButtons)) {
        const button = $(buttonId);
        if (button) {
            button.addEventListener("click", () => {
                initAudio();
                play("click");
                handler();
            });
        }
    }

    // Navigation.
    const backToModes = $("backToModes");
    if (backToModes) {
        backToModes.addEventListener("click", () => {
            play("click");
            hideDifficulty();
        });
    }

    $("homeBtn").addEventListener("click", () => {
        play("click");
        goHome();
    });

    $("homeBtnGame").addEventListener("click", () => {
        play("click");
        goHome();
    });

    $("restartBtn").addEventListener("click", () => {
        play("click");
        // Full restart of the current session.
        goHome();
        // Re-launch the same mode immediately.
        const session = getSession();
        if (session.modeId) {
            launchMode(session.modeId);
            // For AI modes, jump straight back into the game
            // with the remembered difficulty.
        }
    });

    $("soundBtn").addEventListener("click", () => {
        initAudio();
        const enabled = toggleSound();
        $("soundIcon").textContent = enabled ? "🔊" : "🔇";
        if (enabled) play("click");
    });

    $("statsBtn").addEventListener("click", openStats);
    $("settingsBtn").addEventListener("click", openSettings);

    $("fullscreenBtn").addEventListener("click", () => {
        play("click");
        toggleFullscreen();
    });

    // Keyboard shortcuts.
    document.addEventListener("keydown", (event) => {
        if (event.key === "r" || event.key === "R") {
            if ($("game").style.display !== "none") {
                $("restartBtn").click();
            }
        }
        if (event.key === "Escape") {
            if ($("statsPanel").style.display === "block") {
                $("statsPanel").style.display = "none";
            } else if ($("settingsPanel").style.display === "block") {
                $("settingsPanel").style.display = "none";
            } else if ($("game").style.display !== "none") {
                goHome();
            } else if ($("modeSelect") && $("modeSelect").style.display !== "none") {
                showMenu();
            }
        }
    });

    // Block accidental text selection and context menu on game UI.
    document.addEventListener("selectstart", (event) => {
        if (event.target.closest && event.target.closest("input")) return;
        event.preventDefault();
    });

    document.addEventListener("contextmenu", (event) => {
        if (event.target.closest && event.target.closest("input")) return;
        event.preventDefault();
    });

    // Touch: prevent double-tap zoom on the board.
    let lastTouch = 0;
    document.addEventListener("touchend", (event) => {
        const now = Date.now();
        if (now - lastTouch <= 300) {
            event.preventDefault();
        }
        lastTouch = now;
    }, { passive: false });

    // Pause audio on visibility loss.
    platform.onPause(() => {
        // audio ducks automatically via visibility listener in audio.js
    });
    platform.onResume(() => {
        // resume handled by audio.js
    });
}

/* ---------------------------------------------------------
   Fullscreen
   --------------------------------------------------------- */

function toggleFullscreen() {
    const doc = document;
    const element = doc.documentElement;

    if (!doc.fullscreenElement && !doc.webkitFullscreenElement) {
        const request =
            element.requestFullscreen ||
            element.webkitRequestFullscreen;
        if (request) {
            request.call(element).catch(() => { });
        }
    } else {
        const exit = doc.exitFullscreen || doc.webkitExitFullscreen;
        if (exit) {
            exit.call(doc).catch(() => { });
        }
    }
}

/* ---------------------------------------------------------
   Boot
   --------------------------------------------------------- */

async function boot() {
    try {
        initThemeFromProgress();
        initScreens();
        initBoard(boardEl, { onCellClick });
        wireEvents();
    } catch (error) {
        console.error("Boot init failed:", error);
        // Reveal anyway — a broken menu beats a stuck loading screen.
        revealApp();
        return;
    }

    // Initialize the platform, but never let it block the game:
    // SDK init can hang outside the portal environment.
    const initTimeout = new Promise((resolve) => setTimeout(resolve, 4000));
    try {
        await Promise.race([platform.init(), initTimeout]);
    } catch (error) {
        console.warn("Platform init failed — continuing:", error);
    }

    revealApp();
}

function revealApp() {
    loadingScreen.style.display = "none";
    app.style.display = "block";
    showMenu();
    platform.gameLoadingFinished();

    // First-run tutorial — after the lobby is visible.
    maybeShowOnboarding();
}

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", boot);
} else {
    boot();
}
